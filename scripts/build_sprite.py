"""Rebuild lucide_sprite.py: exact lucide path data, copied from lucide-react (ISC licence, https://lucide.dev), as one <svg> of <symbol>s.

usage: python3 build_sprite.py [path/to/lucide-react]   (default ./node_modules/lucide-react)
  e.g. cd "$(mktemp -d)" && npm i lucide-react && python3 /path/to/scripts/build_sprite.py ./node_modules/lucide-react
Add a name to NAMES and re-run when a page needs a new icon. Pages reference icons as <use href="#i-NAME">.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = (
    # diagram lanes and boxes
    'user users monitor cloud brain wrench globe database clipboard-list file-search play layout-grid newspaper search '
    'lightbulb filter file-text target scale gauge history list-checks telescope pen-line code folder-open book-open '
    'shield-check server cpu git-branch bar-chart-3 coins badge-check flask-conical clock list-tree quote '
    # fact labels, status chips, popover
    'info arrow-down-to-line arrow-up-from-line circle-check circle-pause circle-dashed triangle-alert x chevron-right '
    'external-link message-square-text dot '
    # common extras for other pages
    'mail inbox send calendar bell settings lock key check plus minus arrow-right link upload download building-2 '
    'briefcase file folder workflow bot zap activity circle-alert git-merge refresh-cw timer eye pencil table layers '
    'package network hard-drive smartphone laptop sun moon phone map-pin tag star trash-2 copy split merge list-filter '
    'sliders-horizontal user-check handshake landmark receipt wallet trending-up chart-line'
).split()
ATTRS = 'fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"'


def node(root, name, depth=0):
    src = open(f'{root}/dist/esm/icons/{name}.mjs', encoding='utf-8').read()
    m = re.search(r"export \{ default \} from '\./([a-z0-9-]+)\.mjs'", src)
    if m and depth < 3:
        return node(root, m.group(1), depth + 1)
    body = re.search(r'const __iconNode = \[(.*?)\];\s*const ', src, re.S).group(1)
    out = []
    for tag, attrs in re.findall(r'\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]', body):
        kv = [(k, v) for k, v in re.findall(r'(\w+): "([^"]*)"', attrs) if k != 'key']
        out.append(f'<{tag} ' + ' '.join(f'{k}="{v}"' for k, v in kv) + '/>')
    return ''.join(out)


def main():
    root = os.path.realpath(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else './node_modules/lucide-react'))
    if not os.path.isdir(os.path.join(root, 'dist', 'esm', 'icons')):
        sys.exit(f'lucide-react not found at {root}: run `npm i lucide-react` in a temp folder and pass its node_modules/lucide-react')
    syms = ''.join(f'<symbol id="i-{n}" viewBox="0 0 24 24" {ATTRS}>{node(root, n)}</symbol>' for n in NAMES)
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" class="v4sprite" aria-hidden="true" focusable="false" width="0" height="0">'
              + syms + '</svg>')
    with open(os.path.join(HERE, 'lucide_sprite.py'), 'w', encoding='utf-8') as f:
        f.write('"""Generated by build_sprite.py from lucide-react (ISC licence). Do not edit by hand."""\n'
                f'NAMES = {tuple(NAMES)!r}\n'
                f'SPRITE = {sprite!r}\n')
    print('icons', len(NAMES), 'bytes', len(sprite))


if __name__ == '__main__':
    main()
